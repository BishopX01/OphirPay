/**
 * Consolidated API authentication module — single source of truth.
 *
 * Supports:
 *   • Authorization: Bearer <api_key>
 *   • X-API-Key: <api_key>
 *
 * Uses an indexed DB lookup (hash + prefix) — O(1) regardless of key count,
 * unlike the previous pattern that fetched every key and compared in-app.
 */

// ── Key format (#1397) ─────────────────────────────────────────

export * from "@/lib/api-key-format";
import {
  API_KEY_RANDOM_BYTES,
  API_KEY_DIGEST_VERSION,
  API_KEY_LOOKUP_PATTERN,
  calculateCrc32,
  assertValidApiKeyFormat,
  assertMinimumKeyEntropy,
  validateKeyFormat,
  deriveKeyPrefix,
} from "@/lib/api-key-format";

/**
 * Generate a new standardized API key: `op_{env}_{32_hex_bytes}_{4_byte_crc}` (#1397).
 * Defaults to `live` in production and `test` in development/testing.
 *
 * The entropy threshold from the KDF-hardening change is enforced here as
 * well as in the route: a key that could be brute-forced offline must never
 * be minted, no matter which caller asks for one.
 */
export function generateApiKey(options?: { env?: "live" | "test" }): string {
  const env =
    options?.env ??
    (process.env.NODE_ENV === "production" ? "live" : "test");
  const randomHex = crypto
    .randomBytes(API_KEY_RANDOM_BYTES)
    .toString("hex");
  const payload = `op_${env}_${randomHex}`;
  const crc = calculateCrc32(payload);
  const rawKey = `${payload}_${crc}`;
  assertValidApiKeyFormat(rawKey);
  assertMinimumKeyEntropy(rawKey);
  return rawKey;
}

// ── Hashing ────────────────────────────────────────────────────
//
// Three digest formats coexist in the `keyHash` column:
//
//   v2:<argon2id encoded hash>   current — salted, memory-hard KDF
//   v1:<sha256 hex>              previous — unsalted SHA-256, version tagged
//   <sha256 hex>                 legacy   — pre-#701 bare digest
//
// The prefix (`v2:` / `v1:`) lives in the same column, so verification can
// dispatch on the stored format without a schema change and old keys keep
// authenticating while the v2 migration completes.

/** Version tag for the Argon2id digest format. */
export const API_KEY_ARGON2_DIGEST_VERSION = "v2";

/** Prefix stored in `keyHash` for Argon2id digests. */
export const API_KEY_ARGON2_PREFIX = `${API_KEY_ARGON2_DIGEST_VERSION}:`;

/**
 * Argon2id parameters (OWASP Password Storage Cheat Sheet baseline).
 *
 * 19 MiB / t=2 / p=1 is the minimum recommended configuration for Argon2id
 * and is deliberately expensive enough that an attacker who steals the key
 * table cannot mount a fast offline guessing attack.
 */
export const API_KEY_ARGON2_OPTIONS = {
  type: argon2.argon2id,
  memoryCost: 19_456,
  timeCost: 2,
  parallelism: 1,
} as const;

/**
 * Legacy digest: unsalted SHA-256 hex. Retained so keys created before the
 * `v1:` tag (and before the 32-byte format) continue to authenticate.
 */
export function hashApiKey(rawKey: string): string {
  return crypto.createHash("sha256").update(rawKey).digest("hex");
}

/**
 * Previous digest: `v1:<sha256 hex>`. Still verified during the migration
 * window; `hashApiKeyV2` is used for all new keys.
 */
export function hashApiKeyV1(rawKey: string): string {
  return `${API_KEY_DIGEST_VERSION}:${hashApiKey(rawKey)}`;
}

/**
 * Current digest: `v2:<argon2id encoded hash>` — salted with a per-key random
 * salt generated by Argon2 itself.
 */
export async function hashApiKeyV2(rawKey: string): Promise<string> {
  const digest = await argon2.hash(rawKey, API_KEY_ARGON2_OPTIONS);
  return `${API_KEY_ARGON2_PREFIX}${digest}`;
}

/** Constant-time comparison of two digests of equal length. */
function timingSafeDigestEqual(a: string, b: string): boolean {
  const aBuf = Buffer.from(a, "utf8");
  const bBuf = Buffer.from(b, "utf8");
  if (aBuf.length !== bBuf.length) return false;
  return crypto.timingSafeEqual(aBuf, bBuf);
}

/**
 * Verify a raw key against a stored digest in any supported format.
 *
 * Argon2id digests are verified by the KDF; SHA-256 digests (bare or `v1:`)
 * are recomputed and compared in constant time. Malformed stored digests or
 * a missing native argon2 binary return `false` rather than throwing, so an
 * auth lookup fails closed instead of taking the route down.
 */
export async function verifyApiKeyHash(
  rawKey: string,
  storedHash: string
): Promise<boolean> {
  if (storedHash.startsWith(API_KEY_ARGON2_PREFIX)) {
    try {
      return await argon2.verify(
        storedHash.slice(API_KEY_ARGON2_PREFIX.length),
        rawKey
      );
    } catch {
      return false;
    }
  }

  const expected = storedHash.startsWith(`${API_KEY_DIGEST_VERSION}:`)
    ? storedHash.slice(API_KEY_DIGEST_VERSION.length + 1)
    : storedHash;
  return timingSafeDigestEqual(hashApiKey(rawKey), expected);
}

/**
 * Every digest a raw key could have in `keyHash` under the old lookup scheme
 * (hash-only lookup). Kept for tooling/tests; `authenticateRequest` now
 * resolves the key by its indexed `prefix` and verifies the stored digest,
 * which is required for a salted KDF.
 */
export function apiKeyLookupHashes(rawKey: string): string[] {
  return [hashApiKeyV1(rawKey), hashApiKey(rawKey)];
}

/** True when the stored digest still needs upgrading to Argon2id. */
export function needsApiKeyRehash(storedHash: string): boolean {
  return !storedHash.startsWith(API_KEY_ARGON2_PREFIX);
}

// ── Header Extraction ──────────────────────────────────────────

/** Extract a raw API key from Authorization: Bearer or X-API-Key headers. */
export function extractApiKey(request: Request): string | null {
  const authHeader = request.headers.get("authorization");
  if (authHeader) {
    const parts = authHeader.split(" ");
    if (parts.length === 2 && parts[0]!.toLowerCase() === "bearer") {
      return parts[1]!.trim() || null;
    }
  }
  const apiKeyHeader = request.headers.get("x-api-key");
  if (apiKeyHeader) return apiKeyHeader.trim() || null;
  return null;
}

// ── Core Authentication ────────────────────────────────────────

export interface AuthResult {
  userId: string;
  keyId: string;
  keyName: string;
  scopes: string[];
}

/**
 * Authenticate a request against stored API keys.
 *
 * Looks the candidate rows up by the indexed `prefix` (8 chars), then verifies
 * the stored digest. A hash-only lookup is impossible for a salted KDF — the
 * prefix narrows the scan to the handful of rows that could match, and the
 * KDF comparison decides which one (if any) does. Legacy SHA-256 rows verify
 * on the same path and are opportunistically re-hashed to Argon2id on use, so
 * the migration completes without forcing key rotation on integrators.
 */
export async function authenticateRequest(
  request: Request
): Promise<AuthResult | null> {
  const rawKey = extractApiKey(request);
  if (!rawKey) return null;
  // Reject obviously malformed material before hitting the database (#1397).
  // Accepts standardized format with verified CRC, plus legacy formats.
  const isStandardValid = validateKeyFormat(rawKey).valid;
  const isLegacyValid = API_KEY_LOOKUP_PATTERN.test(rawKey);
  if (!isStandardValid && !isLegacyValid) return null;

  const prefix = deriveKeyPrefix(rawKey);

  try {
    const candidates = await prisma.apiKey.findMany({
      where: { prefix, revokedAt: null },
      select: {
        id: true,
        userId: true,
        name: true,
        expiresAt: true,
        scopes: true,
        keyHash: true,
      },
      // A prefix collision across unrelated keys is possible but rare; cap the
      // work an unauthenticated caller can force through the KDF.
      take: 10,
    });

    let apiKey: (typeof candidates)[number] | null = null;
    for (const candidate of candidates) {
      if (await verifyApiKeyHash(rawKey, candidate.keyHash)) {
        apiKey = candidate;
        break;
      }
    }
    if (!apiKey) return null;

    // Check expiration
    if (apiKey.expiresAt && apiKey.expiresAt < new Date()) return null;

    // Opportunistic migration: a valid legacy SHA-256 key is replaced with a
    // salted Argon2id digest. Fire-and-forget — auth latency and availability
    // never depend on the upgrade succeeding (a concurrent rotation can make
    // the update a no-op, which is fine).
    if (needsApiKeyRehash(apiKey.keyHash)) {
      void hashApiKeyV2(rawKey)
        .then((upgraded) =>
          prisma.apiKey.update({
            where: { id: apiKey!.id },
            data: { keyHash: upgraded },
          })
        )
        .catch(() => {});
    }

    // Update lastUsed — fire-and-forget so auth latency is not gated on this write
    prisma.apiKey
      .update({ where: { id: apiKey.id }, data: { lastUsed: new Date() } })
      .catch(() => {});
    prisma.apiKeyRequestLog
      .create({ data: { keyId: apiKey.id } })
      .catch(() => {});

    return {
      userId: apiKey.userId,
      keyId: apiKey.id,
      keyName: apiKey.name,
      scopes: apiKey.scopes ?? [],
    };
  } catch {
    // DB unavailable — reject rather than fail open
    return null;
  }
}

// ── Route Helpers ──────────────────────────────────────────────

/**
 * Middleware wrapper: gate an entire route handler behind API-key auth.
 * Use when the handler does not need to know *which* key was used.
 *
 *   export const GET = withApiAuth(async (req) => { … });
 */
export function withApiAuth(
  handler: (request: Request, ...args: unknown[]) => Promise<Response>,
  required?: ApiScope | ApiScope[]
) {
  return async (request: Request, ...args: unknown[]): Promise<Response> => {
    // Scope-enforced variant
    if (required) {
      const auth = await requireScopes(request, required);
      if (!("userId" in auth)) return auth; // auth is a 401/403 Response
      return handler(request, ...args);
    }

    const auth = await authenticateRequest(request);
    if (!auth) {
      return unauthorizedError(
        "Valid API key required. Use Authorization: Bearer <key> or X-API-Key header."
      );
    }
    return handler(request, ...args);
  };
}

/**
 * Authenticate *and* verify the request's API key carries the required scope(s).
 *
 * Returns the `AuthResult` on success, or a 401/403 `NextResponse` on failure.
 * Check the result with `if (!("userId" in auth)) return auth;` before using it.
 *
 *   const auth = await requireScopes(request, "read:payments");
 *   if (!("userId" in auth)) return auth;   // 401/403 Response
 *   // auth.userId / auth.scopes available
 */
export async function requireScopes(
  request: Request,
  required: ApiScope | ApiScope[]
): Promise<AuthResult | NextResponse> {
  const auth = await authenticateRequest(request);
  if (!auth) {
    return unauthorizedError(
      "Valid API key required. Use Authorization: Bearer <key> or X-API-Key header."
    );
  }

  const requiredList = Array.isArray(required) ? required : [required];
  if (!hasScope(auth.scopes, requiredList)) {
    return forbiddenError(
      `This API key lacks the required scope(s): ${requiredList.join(", ")}. ` +
        `Its effective scopes are: ${auth.scopes.length ? auth.scopes.join(", ") : "(none)"}`,
      { required: requiredList, has: auth.scopes }
    );
  }

  return auth;
}

/**
 * Require authentication and return user context to the caller.
 * Use inside a route handler when you need the authenticated user's identity.
 *
 *   const auth = await requireAuth(request);
 *   if (!("userId" in auth)) return auth;          // auth is an error Response
 *   const { userId } = auth;                       // auth is { userId, keyId }
 */
export async function requireAuth(
  request: Request
): Promise<{ userId: string; keyId: string } | NextResponse> {
  const auth = await authenticateRequest(request);
  if (!auth) {
    return unauthorizedError(
      "Valid API key required. Provide Authorization: Bearer <key> or X-API-Key header."
    );
  }
  return { userId: auth.userId, keyId: auth.keyId };
}
